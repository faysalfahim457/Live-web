'use strict';
// Builds the list of ZIP entries for a collection and streams it. Original captured bytes are never modified;
// the optional reconstructed/ tree contains rewritten copies and is labelled as such.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { ZipWriter } = require('./zip');
const { safeFilename, uniquePath, stripHash, INCOMPRESSIBLE, fmtBytes, extFromMime } = require('./util');
const { pageFileBase } = require('./collector');

const ROOT = 'WebCollector-Project';
const ASSET_DIR = { css: 'assets/css', js: 'assets/js', images: 'assets/images', fonts: 'assets/fonts', other: 'assets/other' };
const SCOPES = new Set(['all', 'page', 'site', 'html', 'css', 'js', 'images', 'fonts', 'selected']);
const MAX_REWRITE_BYTES = 8 * 1024 * 1024;

const h6 = (s) => crypto.createHash('sha1').update(s).digest('hex').slice(0, 6);

// URL of a page -> relative html path (without prefix)
function pagePathFor(urlStr, primaryHost) {
  let u; try { u = new URL(urlStr); } catch { return 'pages/unknown.html'; }
  let segs = u.pathname.split('/').map((s) => safeFilename(s, '_', 80)).filter((s) => s && s !== '_');
  const trailing = u.pathname.endsWith('/') || segs.length === 0;
  const q = u.search ? `-q${h6(u.search)}` : '';
  let file;
  if (trailing) file = `index${q}.html`;
  else {
    const last = segs.pop();
    const m = /^(.*)\.(html?|xhtml)$/i.exec(last);
    file = m ? `${m[1]}${q}.${m[2].toLowerCase()}` : `${last}${q}.html`;
  }
  const dir = segs.join('/');
  const foreign = u.hostname !== primaryHost;
  if (!foreign && !dir && file === 'index.html') return 'index.html';
  return ['pages', foreign ? `_hosts/${safeFilename(u.hostname)}` : '', dir, file].filter(Boolean).join('/');
}

const rel = (from, to) => path.posix.relative(path.posix.dirname(from), to) || path.posix.basename(to);
const decodeEnt = (s) => s.replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#0*39;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>');
const encAttr = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;');

function makeLocalizer(baseUrl, fromPath, map, root = false) {
  return (ref) => {
    const t = ref.trim();
    if (!t || t.startsWith('#') || /^(data:|javascript:|mailto:|tel:|blob:|about:)/i.test(t)) return null;
    let abs; try { abs = new URL(t, baseUrl); } catch { return null; }
    const hash = abs.hash; abs.hash = '';
    const target = map.get(abs.toString());
    return target ? (root ? target : rel(fromPath, target)) + hash : null;
  };
}

function rewriteCss(css, cssUrl, fromPath, map, root = false) {
  const local = makeLocalizer(cssUrl, fromPath, map, root);
  return css
    .replace(/url\(\s*(["']?)([^"')]+?)\1\s*\)/gi, (m, q, u) => { const l = local(u); return l ? `url(${q}${l}${q})` : m; })
    .replace(/@import\s+(["'])([^"']+)\1/gi, (m, q, u) => { const l = local(u); return l ? `@import ${q}${l}${q}` : m; });
}

function rewriteHtml(html, pageUrl, fromPath, map, root = false) {
  let base = pageUrl;
  const bm = /<base\s[^>]*?href\s*=\s*(?:"([^"]*)"|'([^']*)')[^>]*>/i.exec(html);
  if (bm) { try { base = new URL(bm[1] ?? bm[2], pageUrl).toString(); } catch { /* keep */ } html = html.replace(bm[0], ''); }
  const local = makeLocalizer(base, fromPath, map, root);
  html = html.replace(/(\s(?:src|href|poster|data-src|data-original|data-lazy-src)\s*=\s*)(?:"([^"]*)"|'([^']*)')/gi, (m, pre, a, b) => {
    const l = local(decodeEnt(a ?? b)); return l ? `${pre}"${encAttr(l)}"` : m;
  });
  html = html.replace(/(\s(?:srcset|data-srcset)\s*=\s*)(?:"([^"]*)"|'([^']*)')/gi, (m, pre, a, b) => {
    const parts = decodeEnt(a ?? b).split(',').map((p) => {
      const t = p.trim(); if (!t) return t;
      const i = t.search(/\s/); const u = i < 0 ? t : t.slice(0, i); const d = i < 0 ? '' : t.slice(i);
      const l = local(u); return (l || u) + d;
    });
    return `${pre}"${encAttr(parts.join(', '))}"`;
  });
  html = html.replace(/(<style[^>]*>)([\s\S]*?)(<\/style>)/gi, (m, a, css, c) => a + rewriteCss(css, base, fromPath, map, root) + c);
  html = html.replace(/(\sstyle\s*=\s*)"([^"]*)"/gi, (m, pre, css) => `${pre}"${encAttr(rewriteCss(decodeEnt(css), base, fromPath, map, root))}"`);
  for (let i = 0; i < 3; i++) html = html.replace(/(<(?:link|script)\b[^>]*?)\s(?:integrity|crossorigin)(?:\s*=\s*(?:"[^"]*"|'[^']*'|[^\s>]+))?/gi, '$1');
  const banner = root ? `<!-- HOST-READY COPY generated by WebCollector Studio from ${pageUrl}. Files are stored at the same paths as on the original site; upload the site/ folder contents to the ROOT of a web host. -->` : `<!-- RECONSTRUCTED COPY generated by WebCollector Studio from the DOM snapshot of ${pageUrl}. Links were rewritten to local relative paths. Originals are under /original and /snapshots. -->`;
  return /^<!doctype[^>]*>/i.test(html) ? html.replace(/^(<!doctype[^>]*>)/i, `$1\n${banner}`) : `${banner}\n${html}`;
}


// ---------- host-ready mirror: files stored at the same paths as on the original site ----------
const urlPath = (p) => '/' + p.split('/').map(encodeURIComponent).join('/');
function mirrorFile(rawUrl, mime, primaryHost, isPage) {
  let u; try { u = new URL(rawUrl); } catch { return isPage ? 'index.html' : 'file'; }
  const segs = u.pathname.split('/').map((x) => safeFilename(x, '_', 100)).filter((x) => x && x !== '_');
  const trailing = u.pathname.endsWith('/') || segs.length === 0;
  let file = trailing ? 'index' : segs.pop();
  if (isPage) { if (!/\.(html?|xhtml)$/i.test(file)) { if (trailing) file = 'index.html'; else { segs.push(file); file = 'index.html'; } } }
  else if (!path.extname(file)) { const e = extFromMime(mime); if (e) file += `.${e}`; }
  const prefix = u.hostname === primaryHost ? [] : ['_external', safeFilename(u.hostname, 'host')];
  return [...prefix, ...segs, file].join('/');
}
function addSiteMirror(entries, collector, selected, pagesArr, primaryHost, { scope, pageId, prefix }) {
  const used = new Set(); const map = new Map(); const pathOf = new Map();
  const assets = selected.filter((r) => r.type !== 'html' && r.type !== 'screenshots' && (r.kind === 'network' || r.kind === 'sourcemap'));
  for (const r of assets) {
    const p = uniquePath(used, '', mirrorFile(r.rawUrl, r.mime, primaryHost, false)); pathOf.set(r.id, p);
    map.set(stripHash(r.rawUrl), urlPath(p)); for (const a of r.aliasRaw || []) map.set(a, urlPath(p));
  }
  const pages = pagesArr.filter((p) => (scope !== 'page' || p.id === pageId) && (p.originalId || p.snapshotIds.length));
  const pagePath = new Map();
  for (const p of pages) {
    const f = uniquePath(used, '', mirrorFile(p.key, 'text/html', primaryHost, true)); pagePath.set(p.id, f);
    map.set(p.key, f.endsWith('/index.html') ? urlPath(f.slice(0, -'index.html'.length)) : f === 'index.html' ? '/' : urlPath(f));
  }
  for (const r of assets) {
    const to = prefix + pathOf.get(r.id);
    if (r.type === 'css' && r.size <= MAX_REWRITE_BYTES) entries.push({ name: to, mtime: new Date(r.collectedAt), bytes: r.size, buffer: () => Buffer.from(rewriteCss(fs.readFileSync(collector.filePath(r), 'utf8'), r.rawUrl, pathOf.get(r.id), map, true), 'utf8') });
    else entries.push({ name: to, path: collector.filePath(r), store: INCOMPRESSIBLE.has(r.mime), crc32: r.crc32, mtime: new Date(r.collectedAt), bytes: r.size });
  }
  for (const p of pages) {
    // The ORIGINAL server response is used (scripts re-render the page exactly as on the real site); the DOM snapshot is only a fallback.
    const src = collector.resources.get(p.originalId) || collector.resources.get(p.snapshotIds[p.snapshotIds.length - 1]); if (!src || src.size > MAX_REWRITE_BYTES) continue;
    const fp = pagePath.get(p.id);
    entries.push({ name: prefix + fp, mtime: new Date(src.collectedAt), bytes: src.size, buffer: () => Buffer.from(rewriteHtml(fs.readFileSync(collector.filePath(src), 'utf8'), p.key, fp, map, true), 'utf8') });
  }
  entries.push({ name: prefix + 'README-HOSTING.txt', buffer: Buffer.from('HOST-READY SITE MIRROR (modified output)\n\nFiles are stored at the same paths they had on the original site (for example /m/app.js is m/app.js), so absolute links such as "/m/app.js"\nkeep working. Upload the CONTENTS of this folder to the ROOT of a web host (public_html / htdocs / web root), not to a sub-folder.\n\nPages use the original server HTML, so scripts rebuild them the same way as on the real site. Links to collected files on other hosts were rewritten to\n/_external/<host>/... Data that scripts load from the original server\'s API (login, balances, live content) is not part of a static copy and will not work.\nUse only for sites you are authorised to copy.\n') });
  return { pages: pages.length, files: assets.length };
}

function selectResources(collector, { scope, ids, pageId }) {
  let all = [...collector.resources.values()];
  switch (scope) {
    case 'page': all = all.filter((r) => r.pages.includes(pageId)); break;
    case 'html': case 'css': case 'js': case 'images': case 'fonts': all = all.filter((r) => r.type === scope); break;
    case 'selected': { const s = new Set(ids); all = all.filter((r) => s.has(r.id)); break; }
    default: break;
  }
  return all.sort((a, b) => Number(a.id.slice(1)) - Number(b.id.slice(1)));
}

function buildPlan(collector, session, { scope = 'all', ids = [], pageId = null, reconstructed = true } = {}) {
  if (!SCOPES.has(scope)) throw Object.assign(new Error('Unknown export scope.'), { code: 'BAD_REQUEST' });
  const selected = selectResources(collector, { scope: scope === 'site' ? 'all' : scope, ids, pageId });
  if (!selected.length) throw Object.assign(new Error('There is nothing to export for this selection yet.'), { code: 'NOTHING_TO_EXPORT' });
  const pagesArr = [...collector.pages.values()];
  const primaryHost = (() => { try { return new URL(pagesArr[0] ? pagesArr[0].key : session.startUrl).hostname; } catch { return ''; } })();
  const used = new Set(); const entries = []; const zipPathOf = new Map(); const relOf = new Map();
  const pageById = new Map(pagesArr.map((p) => [p.id, p]));
  if (scope === 'site') {
    const out = []; const r = addSiteMirror(out, collector, selected, pagesArr, primaryHost, { scope: 'all', pageId, prefix: '' });
    if (!r.pages && !r.files) throw Object.assign(new Error('There is nothing to export for this selection yet.'), { code: 'NOTHING_TO_EXPORT' });
    return { entries: out, count: out.length, scope, selected: selected.length };
  }

  for (const r of selected) {
    let name;
    if (r.kind === 'snapshot') {
      const pg = r.pages[0] && pageById.get(r.pages[0]);
      const slug = pg ? pageFileBase(pg.key) : 'page';
      name = uniquePath(used, `snapshots/dom/${slug}`, `${r.collectedAt.replace(/[:.]/g, '-')}-${r.sha256.slice(0, 8)}.html`);
    } else if (r.kind === 'screenshot') {
      name = uniquePath(used, 'snapshots/screenshots', `${r.collectedAt.replace(/[:.]/g, '-')}-${r.filename}`);
    } else if (r.type === 'html') {
      const sub = r.isFrame ? `original/pages/_frames/${safeFilename(r.filename)}` : `original/${pagePathFor(r.rawUrl, primaryHost)}`;
      name = uniquePath(used, '', sub);
    } else {
      const d = r.kind === 'inline-style' ? `${ASSET_DIR.css}/inline` : ASSET_DIR[r.type] || ASSET_DIR.other;
      name = uniquePath(used, `original/${d}`, r.filename);
      relOf.set(r.id, name.slice('original/'.length));
    }
    zipPathOf.set(r.id, name);
    entries.push({ name, path: collector.filePath(r), store: INCOMPRESSIBLE.has(r.mime), crc32: r.crc32, mtime: new Date(r.collectedAt), bytes: r.size });
  }

  // --- reconstructed static copy (optional, separate tree) ---
  const reconPaths = {};
  if (reconstructed && (scope === 'all' || scope === 'page')) {
    const urlMap = new Map();
    const assets = selected.filter((r) => r.type !== 'html' && r.type !== 'screenshots' && (r.kind === 'network' || r.kind === 'sourcemap'));
    for (const r of assets) { urlMap.set(stripHash(r.rawUrl), relOf.get(r.id)); for (const a of r.aliasRaw || []) urlMap.set(a, relOf.get(r.id)); }
    const reconUsed = new Set(); const pagePaths = new Map();
    const reconPages = pagesArr.filter((p) => (scope === 'all' || p.id === pageId) && (p.snapshotIds.length || p.originalId));
    for (const p of reconPages) { const pp = uniquePath(reconUsed, '', pagePathFor(p.key, primaryHost)); pagePaths.set(p.id, pp); urlMap.set(p.key, pp); }
    for (const r of assets) {
      const to = `${ROOT ? '' : ''}reconstructed/${relOf.get(r.id)}`;
      reconPaths[r.id] = to; reconUsed.add(relOf.get(r.id).toLowerCase());
      if (r.type === 'css' && r.size <= MAX_REWRITE_BYTES) {
        entries.push({ name: to, mtime: new Date(r.collectedAt), bytes: r.size, buffer: () => Buffer.from(rewriteCss(fs.readFileSync(collector.filePath(r), 'utf8'), r.rawUrl, relOf.get(r.id), urlMap), 'utf8') });
      } else entries.push({ name: to, path: collector.filePath(r), store: INCOMPRESSIBLE.has(r.mime), crc32: r.crc32, mtime: new Date(r.collectedAt), bytes: r.size });
    }
    for (const p of reconPages) {
      const srcId = p.snapshotIds.length ? p.snapshotIds[p.snapshotIds.length - 1] : p.originalId;
      const src = collector.resources.get(srcId); if (!src) continue;
      const pp = pagePaths.get(p.id); reconPaths[`page:${p.id}`] = `reconstructed/${pp}`;
      if (src.size > MAX_REWRITE_BYTES) continue;
      entries.push({ name: `reconstructed/${pp}`, mtime: new Date(src.collectedAt), bytes: src.size, buffer: () => Buffer.from(rewriteHtml(fs.readFileSync(collector.filePath(src), 'utf8'), p.key, pp, urlMap), 'utf8') });
    }
    entries.push({ name: 'reconstructed/README-RECONSTRUCTED.txt', buffer: Buffer.from('RECONSTRUCTED STATIC COPY (modified output)\n\nEverything in this folder was generated by WebCollector Studio: HTML comes from rendered DOM snapshots and\nreferences to collected files were rewritten to local relative paths; CSS url()/@import references were rewritten too.\nScripts are included as captured and may not behave offline. The untouched captured bytes are in ../original and ../snapshots.\n') });
  }

  if (scope === 'all' || scope === 'page') addSiteMirror(entries, collector, selected, pagesArr, primaryHost, { scope, pageId, prefix: 'site/' });

  // --- metadata ---
  const zipOrNull = (id) => zipPathOf.get(id) || null;
  const meta = {
    pages: pagesArr.filter((p) => scope === 'all' || scope !== 'page' || p.id === pageId).map((p) => ({
      url: p.url, title: p.title, status: p.status, files: p.fileIds.size, error: p.error, firstVisit: new Date(p.firstVisit).toISOString(),
      original: zipOrNull(p.originalId), snapshots: p.snapshotIds.map(zipOrNull).filter(Boolean), screenshots: p.screenshotIds.map(zipOrNull).filter(Boolean), reconstructed: reconPaths[`page:${p.id}`] || null,
    })),
    resources: selected.map((r) => ({
      id: r.id, originalUrl: r.url, alsoSeenAt: r.alsoSeenAt, type: r.type, kind: r.kind, origin: r.kind === 'network' || r.kind === 'sourcemap' ? 'original-capture' : 'generated-by-collector',
      filename: r.filename, mime: r.mime, size: r.size, httpStatus: r.httpStatus, collectedAt: r.collectedAt, sourcePage: r.sourcePage, sha256: r.sha256,
      zipPath: zipPathOf.get(r.id), reconstructedPath: reconPaths[r.id] || null,
    })),
  };
  const stats = collector.stats();
  const report = {
    generator: 'WebCollector Studio', generatedAt: new Date().toISOString(), scope, session: { startedAt: new Date(session.createdAt).toISOString(), startUrl: session.startUrlRedacted },
    statistics: { pagesVisited: stats.pages, filesInCollection: stats.files, filesInThisExport: selected.length, bytesInThisExport: selected.reduce((a, r) => a + r.size, 0), duplicatesSkipped: stats.duplicates, failedRequests: stats.failed, skippedOverLimitOrPrivate: stats.skipped, byType: { html: stats.html, css: stats.css, js: stats.js, images: stats.images, fonts: stats.fonts, other: stats.other, screenshots: stats.screenshots } },
    limits: { maxFileBytes: collector.cfg.maxFileBytes, maxTotalBytes: collector.cfg.maxTotalBytes, maxFiles: collector.cfg.maxFiles, storageLimitReached: stats.full },
    privacy: 'Cookies, storage, request headers, credentials and password/token field values are not collected. URL credentials are removed and secret-looking query values replaced with REDACTED.',
    failures: collector.failureList(),
    layout: { 'original/': 'Captured bytes exactly as received (initial HTML responses, assets).', 'snapshots/': 'Rendered DOM snapshots and screenshots taken by the collector.', 'site/': 'Host-ready mirror: files at the same paths as the original site (upload contents to a web root).', 'reconstructed/': 'OPTIONAL modified static copy with rewritten local links.', 'metadata/': 'pages.json, resources.json' },
  };
  const readme = `WebCollector Studio export (${report.generatedAt})\nScope: ${scope}\nFiles in this export: ${selected.length} (${fmtBytes(report.statistics.bytesInThisExport)})\n\nFolders\n  original/       Captured resources, byte-for-byte as received. Not modified.\n                  index.html + pages/ are the initial HTML responses; assets/ holds css, js, images, fonts, other.\n  snapshots/      Rendered DOM snapshots (what the browser showed after JavaScript ran) and screenshots.\n  site/           Host-ready mirror: files at the SAME PATHS as on the original site (/m/app.js -> site/m/app.js). Upload its contents to a web root.
  reconstructed/  Optional static copy with links rewritten to local paths. This is MODIFIED output.\n  metadata/       pages.json and resources.json map every file to its source URL, hash and page.\n  collector-report.json  Statistics, limits and failures.\n\nOnly publicly loaded frontend files were collected. Use this tool only on sites you are authorised to inspect.\n`;
  entries.push({ name: 'metadata/pages.json', buffer: Buffer.from(JSON.stringify(meta.pages, null, 2)) });
  entries.push({ name: 'metadata/resources.json', buffer: Buffer.from(JSON.stringify(meta.resources, null, 2)) });
  entries.push({ name: 'collector-report.json', buffer: Buffer.from(JSON.stringify(report, null, 2)) });
  entries.push({ name: 'README.txt', buffer: Buffer.from(readme) });
  return { entries, count: entries.length, scope, selected: selected.length };
}

async function streamExport(plan, out, onProgress) {
  const zip = new ZipWriter(out);
  let done = 0;
  for (const e of plan.entries) {
    const name = `${ROOT}/${e.name}`;
    if (e.buffer) await zip.addFile(name, { buffer: typeof e.buffer === 'function' ? e.buffer() : e.buffer, mtime: e.mtime });
    else await zip.addFile(name, { path: e.path, store: e.store, crc32: e.crc32, mtime: e.mtime });
    done++;
    onProgress({ filesDone: done, filesTotal: plan.entries.length, bytes: zip.offset });
  }
  await zip.finish();
  return zip.offset;
}

module.exports = { buildPlan, streamExport, pagePathFor, rewriteHtml, rewriteCss, SCOPES };
